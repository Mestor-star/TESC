/* ============================================================
   事件补充设定 —— canon 原文通道（按事件粒度的细节注入）
   ------------------------------------------------------------
   给「剧情推进」导演系统在当前事件期间**确定性**提供的原文细节：
   由 buildDirectorSystem 在拼装提示词时直接读 eventNotesOf(evId)，
   不经世界书关键词扫描，因此每回合必达；同时并入「事件回顾」
   世界书词条，使该事件完成后的短信侧也可引用同一份摘录。

   铁律（与全项目一致）：内容须**逐字摘录**自源文献，绝不新增、
   改写或补全设定；拿不准就留空，留空即无副作用、行为零差异。

   键 = 事件 id（如 'v1-1' / 'v2-4' / 's1-6'）。数组里每项为一段原文。
   ============================================================ */

export const EVENT_NOTES: Record<string, readonly string[]> = {
  // 填法示例（启用时请逐字摘录原文）：
  // 'v1-1': [
  //   '……（这一段原文）……',
  //   '……（另一段原文，如需多段）……',
  // ],
}

/** 取某事件的原文摘录（空数组 = 无补充设定） */
export function eventNotesOf(id: string): string[] {
  const notes = EVENT_NOTES[id]
  return notes && notes.length ? [...notes] : []
}
