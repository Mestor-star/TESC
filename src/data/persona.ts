/** 取某角色的卡面；无登记返回 undefined */
export function personaCardOf(id: string): PersonaCard | undefined {
  return PERSONA_CARDS[id]
}

/**
 * 渲染为人物卡正文行（分层节段；无卡或全空 → null，由调用方回退旧 flat 档案）。
 */
export function personaCardLines(id: string): string[] | null {
  const card = PERSONA_CARDS[id]
  if (!card) return null
  const out: string[] = []
  if (card.tagline) out.push(card.tagline)
  for (const s of card.sections) {
    if (!s.lines.length) continue
    out.push(`〔${s.title}〕`)
    for (const l of s.lines) out.push(`· ${l}`)
  }
  return out.length ? out : null
}
