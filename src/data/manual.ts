/* ============================================================
   观测终端操作手册
   ------------------------------------------------------------
   智库里的文本教程。**官方口径**（不是梅芙的话 —— 引导是她在讲，
   手册是委员会发的文档）：陈述句、无人称、无比喻、结论在前；
   每个开关管什么、按下去发生什么，一条一条写定，不带语气。

   与 LORE 分开的理由：LORE 会经 lib/loreseed.ts 并进内置世界书、
   跟着提示词一起送出去；手册讲的是这台终端怎么用，不该混进设定里。
   所以它单独放一份只读数据，只在智库页陈列。

   每条都得**照着终端现在的样子写**：写「按某键」就得真有那个键。
   终端改了、这里没改，就是文档在骗人 —— 改动时一并核对。
   ============================================================ */

