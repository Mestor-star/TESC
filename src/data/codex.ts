/** 判断长串中是否出现「独立」的编号（两侧不接数字，避免 951 误中 9510） */
function hasCode(text: string, code: string): boolean {
  const i = text.indexOf(code)
  if (i < 0) return false
  const pre = i > 0 ? text[i - 1] : ''
  const post = i + code.length < text.length ? text[i + code.length] : ''
  return !/\d/.test(pre) && !/\d/.test(post)
}

/**
 * 把时间线段的实体标注（如「NO.3922 灵魂蓄积器TM」）解析为终末图鉴条目 id。
 * 命中即视为「推进剧情自动登记」。匹配不到返回 null（该实体未收录图鉴）。
 */
export function resolveEntityToCodexId(ent: string): string | null {
  for (const e of CODEX) {
    if (e.name && (ent.includes(e.name) || e.name.includes(ent))) return e.id
  }
  for (const e of CODEX) {
    if (e.no && e.no !== '' && e.no !== '？？？' && hasCode(ent, e.no)) return e.id
  }
  return null
}

/**
 * 从图鉴别名里取最贴切的登记名（自记条目展示用）。
 */
export function displayClassLabel(e: EndEntry): string {
  return e.classes[0] ?? '异法'
}

