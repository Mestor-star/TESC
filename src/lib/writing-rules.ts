/* ============================================================
   文风 · 不要 AI 味（lib/writing-rules.ts）
   ------------------------------------------------------------
   这一节管的是**笔法**：模型不提醒就一定会写出来的那几套句子，以及它们该换成什么。

   为什么单独成文件：它与 plot.ts 里那几节（导演铁律 / 台词行契约 / 收尾自检）
   同是「正文怎么写」，但换一处、改一句都要能在提示词里一眼找到原文，
   所以收成一个常量由 plot.ts 引用，不散在模板串中间。

   与已有的两份**并行、不重复**：
     · presets/*.json 的「反八股」管投石句、瞳孔骤缩、嘴角勾起那一类**词与句**
       （那份只在用户套用预设时才进提示词，缺了它这一节也不能缺）；
     · lib/worldrules.ts 的笔法条目管私密场面怎么细。
   这里补的是它没点名的三处 —— 假靶子（不是 A 而是 B）、同义替换、无关处硬凑，
   外加收尾与落笔前自检。新增与它们同时成立，不覆盖其中任何一条。

   两份出口，**同源**：
     · `ANTI_AI_STYLE`      —— 正文体（主线推演、约会专线）。九条全给。
     · `ANTI_AI_STYLE_SHORT` —— 短消息体（短信单聊 / 群聊回执）。同一条条文的**子集**，
       只是挑掉那几条只对成段正文成立的（无关处硬凑、具体优先于抽象、落笔前自检）。
       规则文本一个都不改写 —— 子集从同一张表里挑，改一条两处一起改。
   ============================================================ */

/**
 * 九条条文的**唯一出处**。整节与短版都从这里拼，不另写一套。
 *
 * 写法上的分寸：反例给到**能认出**那么短就够了 —— 写长了模型会把它当成「可以这样写」的样例；
 * 每条都跟一句正面改法，是因为只禁不给替身，模型就退回它最熟的那套句式。
 */
const RULES = {
  /** 假靶子：先否一个没人会做的判断，再端出真话 */
  falseTarget: `· 禁「不是 A，而是 B」的**假靶子** —— 先否一个没人会做的判断，再端出真话，读着像在跟人对稿：
  反例「不是因为她害怕，而是因为她早就知道。」→ 把 B 直接写成事实：「她早就知道。手缩在袖子里，指甲掐进掌心。」
  反例「他不是不想回答，只是不知道从哪儿开口。」→「他张了下嘴，又闭上，去够桌上的杯子。」`,
  /** 同义替换：两个词说同一件事，还拿「而是」拧一下 */
  synonym: `· 禁**同义替换**：两个词说的是同一件事，还拿「而是」「其实」拧一下 —— 删掉一半，留更具体的那半。`,
  /** 无关处硬凑：只对成段正文成立，短消息里挑掉 */
  pad: `· 禁**无关处硬凑**，含「不是 X。不是 Y。只是 Z。」这种三连变体：前后本来没关系，硬凑成对照，两件事就都写虚了。`,
  /** 自问自答 + 破折号连用 */
  selfAsk: `· 禁自问自答（「你有没有想过……」）与破折号连用：破折号一回合最多两处，只用来打断或插入，不用它表余韵。`,
  /** 句句工整、排比、心理旁白 —— 短消息一样犯 */
  rhythm: `· 句句工整最像 AI：允许短句、半句、说错再改口、突然停住；**三段以上同构排比不要写**。
  心理词少用 ——「他感到愤怒／不安」换成他手上那一个动作、说出口的那一句话。`,
  /** 具体优先于抽象：要成段的场面才有落点，短消息里挑掉 */
  concrete: `· **具体优先于抽象**：这一回合至少有一件事落到能摸到的实处 —— 手上的油、铁栏杆的凉、走廊的潮味、绷带缠得紧不紧。
  「气氛紧张」不算；杯沿在桌面上磕出响声、谁的手抖了一下才算。`,
  /** 对白要有人味：群聊里每人分得开，全靠这一条 */
  voice: `· **对白要有人味**：允许废话、停顿、抢话、答非所问。不同角色的用词与句长要分得开
  （爱绕长句的／一句只说四五个字的／爱骂人的／把话咽回去的）—— 名字遮住也该认出是谁在说。`,
  /** 总结式收尾 */
  ending: `· 禁**总结式收尾**：不许用一段抽象升华给这一回合收口 ——「这一刻，他终于明白了……」「而这，才刚刚开始」。
  收在正在做的事、一句没说完的话、一个具体的物上；收得住就停，不必再添一句感想。`,
  /** 落笔前自检：短消息里挑掉（一到三句，回头看一遍收益低、篇幅不值） */
  selfCheck: `· **输出前自检**（不要把自检过程写出来）：回头找这一回合里**最像 AI 的三处**，照上面几条改掉再交。
  找不出来就是还没看够 —— 至少盯一眼排比、心理旁白、总结式收尾这三处最容易出问题的地方。`,
}

const HEAD = '【文风 · 不要 AI 味】（只管正文怎么写；与上面各节并行，不覆盖其中任何一条）'

/**
 * 文风 · 不要 AI 味。拼进主线推演的 system 提示词（见 lib/plot.ts 的 buildDirectorSystem）
 * 与约会专线的 system 提示词（见 lib/rendezvous.ts 的 rendezvousPrompt）。
 */
export const ANTI_AI_STYLE = `${HEAD}
${RULES.falseTarget}
${RULES.synonym}
${RULES.pad}
${RULES.selfAsk}
${RULES.rhythm}
${RULES.concrete}
${RULES.voice}
${RULES.ending}
${RULES.selfCheck}`

/**
 * 短消息那一版：同一条条文的子集，只留**一到三句也会犯**的那几条。
 *
 * 为什么短：短信 / 群聊回执一次只出一到三句，整节九条压在它上面，篇幅就比正文本身长了；
 * 而且「无关处硬凑」「具体优先于抽象」「落笔前自检」三条要的是成段的场面与回头改稿，
 * 在这儿没有落点。留下的六条（假靶子、同义替换、自问自答、工整排比与心理词、
 * 对白分得开、总结式收尾）都是一两句话里照样会漏出来的。
 */
export const ANTI_AI_STYLE_SHORT = `【文风 · 不要 AI 味 · 短消息】（只管这几句怎么打；与上面各节并行，不覆盖其中任何一条）
${RULES.falseTarget}
${RULES.synonym}
${RULES.selfAsk}
${RULES.rhythm}
${RULES.voice}
${RULES.ending}`
