/* ============================================================
   输出预算（max_tokens）—— 唯一的真源
   ------------------------------------------------------------
   以前这个数散在三处各写各的：导入器夹到 64000、设置页的输入框夹到 32000、
   通道缺省 1500。于是同一份预设从不同入口进来，落地的值不一样；
   而 1500 那一档在思考型通道上根本不够 —— 预算先被内部思考吃光，
   正文一个字没写就被长度掐断（日志里就是「达长度上限但正文为空」）。

   这里只放三个数与一个收口函数，谁要用谁来读。
   ============================================================ */

/** 下限：一条短信（一到三句）也够；比这更低只可能是手滑 */
export const MIN_BUDGET = 256
/** 上限：再高就该去调模型自己的输出上限，而不是留着界面替它挡 */
export const MAX_BUDGET = 65536
/**
 * 缺省（建议值）30000。
 * 注意它是**建议**不是保证：个别通道自己的输出上限比这低，
 * 超过时上游会明确报错（照它说的往下调即可），而不是悄悄截断。
 */
export const DEFAULT_BUDGET = 30000

/**
 * 我们自己塞进去过的历史缺省值 —— 归位那一步认的就是这一串。
 *
 * 8000 也在其中：内置预设的 JSON 一直到 9976705 之前都写着 `openai_max_tokens: 8000`，
 * 那是**我们发的缺省**，不是用户挑的数。它这一档在思考型通道上照样不够
 * （预算先被内部思考吃光，正文一个字没写就被长度掐断），所以要和 1500 一样抬上来。
 * 漏掉它的后果很隐蔽：预设内容换成 30000 了，可**已经套用过旧预设的那台机器**
 * 通道里存的仍是 8000，界面上看不出任何异常 —— 用户只会觉得「默认的 8000 根本不够」。
 *
 * 用户自己打的数（4096 / 65536 …）不在此列，一个都不动。
 */
export const LEGACY_BUDGETS: readonly number[] = [1500, 8000]

/**
 * 把任意输入收进允许区间。
 * @param n  想设的值（NaN / 非数字 / 低于下限 → 用缺省）
 * @param fb 缺省值
 */
export function clampBudget(n: number, fb = DEFAULT_BUDGET): number {
  return Number.isFinite(n) && n >= MIN_BUDGET ? Math.min(MAX_BUDGET, Math.round(n)) : fb
}
