/** 全部引导，按出场顺序排 */
export const TOURS: GuideTour[] = [BOOT, ...MODULES, BATTLE, BOSS]

export interface GuideState {
  /** 已经讲完（或跳过）的引导 id */
  done: string[]
  /** 玩家按过「跳过教程」—— 教程部分不再出现 */
  skipped: boolean
}

const KEY = 'zts-guide:v1'

export function readGuide(): GuideState {
  try {
    const raw = localStorage.getItem(KEY)
    if (!raw) return { done: [], skipped: false }
    const p = JSON.parse(raw) as Partial<GuideState>
    return {
      done: Array.isArray(p.done) ? p.done.filter((x): x is string => typeof x === 'string') : [],
      skipped: p.skipped === true,
    }
  } catch {
    return { done: [], skipped: false }
  }
}

function write(g: GuideState): void {
  try { localStorage.setItem(KEY, JSON.stringify(g)) } catch { /* 隐私模式：讲一次就算了 */ }
}

/** 一段讲完了：记下来，不再重播 */
export function markDone(id: string): GuideState {
  const g = readGuide()
  if (!g.done.includes(id)) g.done.push(id)
  write(g)
  return g
}

/** 跳过教程：整段教程再不出现（boss 讲解不在其中 —— 那个该讲还得讲） */
export function skipTutorial(): GuideState {
  const g = readGuide()
  g.skipped = true
  write(g)
  return g
}

/** 重置世界时一并清掉：新的一轮，梅芙从头再讲一遍 */
export function resetGuide(): void {
  try { localStorage.removeItem(KEY) } catch { /* 同上 */ }
}

/**
 * 读档时把这档当时的进度放回去。
 * 引导进度是**跟着存档走**的：他从哪一档读的，梅芙就接着那一档讲到哪里，
 * 而不是按本机上最后玩过的那一档算。快照里没有这一项（改动之前存的老档）就不动。
 */
export function writeGuide(g: GuideState | undefined): void {
  if (!g) return
  write({
    done: Array.isArray(g.done) ? g.done.filter((x): x is string => typeof x === 'string') : [],
    skipped: g.skipped === true,
  })
}

/**
 * 现在该讲哪一段。
 * @param view    当前模块
 * @param epDone  已收束的事件
 * @param inBattle 是否正处在作战屏（boss 讲解只在场上讲）
 * @param bossUp  场上是否出现了 boss 级敌体
 */
export function nextTour(
  view: string,
  epDone: Record<string, true>,
  inBattle: boolean,
  bossUp: boolean,
): GuideTour | null {
  const g = readGuide()
  const seen = (id: string) => g.done.includes(id)
  const tutorialOpen = !g.skipped && !epDone[TUTORIAL_END]

  /* 作战屏上的两段，次序是钉死的：先讲这一屏本身，再讲 boss。
     倒过来讲的话，boss 那一段说的「打断咏唱」「槽满接招」在玩家眼里没有落脚点 ——
     他连共鸣槽在哪都还没认出来。这一段仍然归教程管（tutorial: true），
     玩家按过「跳过教程」就不讲；boss 那一段不归教程管，该讲还得讲。 */
  if (inBattle && tutorialOpen && !seen(BATTLE.id)) return BATTLE
  // boss 讲解排在教程模块之前：正在挨打的时候没人想听模块介绍
  if (inBattle && bossUp && !seen(BOSS.id)) return BOSS
  if (!tutorialOpen) return null
  if (!seen(BOOT.id)) return BOOT
  const t = MODULES.find((m) => m.view === view && !seen(m.id))
  return t ?? null
}
