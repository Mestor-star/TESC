/** 中文读法，只到 99 —— 侧栏念到「十二」就够了，别为这一句引一套数字库 */
const CN_DIGIT = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九']
function cnCount(n: number): string {
  if (n < 10) return CN_DIGIT[n] ?? String(n)
  const tens = Math.floor(n / 10)
  const ones = n % 10
  return (tens === 1 ? '十' : (CN_DIGIT[tens] ?? '') + '十') + (ones ? (CN_DIGIT[ones] ?? '') : '')
}

