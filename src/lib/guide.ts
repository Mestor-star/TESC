/* ============================================================
   引导 —— 梅芙莉莎 · 简别科娃手把手教你用这台终端
   ------------------------------------------------------------
   口径取自原作：她是恋兔队唯一的常识担当、战术副官，理性沉着。
   她说话的样本长这样 ——
     「任务了解。那我们走吧，言万同学。」
     「我们到达深海底部的『异界』。前方确认到不明的巨型终末。
       接下来非常危险。请在我们下次联络后，发动沙姆希尔。」
   短句、陈述句、现在时、结论在前。所以这个引导的口气就是她的战报体：
   不抒情、不绕弯、不留二义；每个按键管什么、按下去发生什么，一条一条说死。

   两条线：
     · 教程（boot + 十一个模块）：从开局讲到第一卷「脏器公寓」收束为止。
       每到一个模块第一次，梅芙出来讲这个模块是干什么的。
       可以选择跳过 —— 跳过之后她在整个教程期都不再开口。
     · 讲解（boss）：教程结束后她本来就不说话了，只有一个例外：
       撞上 boss 级敌体（危险度 ≥ ultStage）时，她出来把这一仗讲清楚 ——
       终结技能怎么破，以及敌体挂在我方身上的那些机制各是什么、怎么解。

   讲法：事无巨细。每个模块「有什么、按哪儿、按了会怎么样」，全部交底。

   进度落在本地：zts-guide:v1 —— 哪些讲完了、跳没跳。
   ============================================================ */

/** 气泡挂在锚点的哪一侧 */
export type GuideSide = 'top' | 'bottom' | 'left' | 'right'

export interface GuideStep {
  /** 锚点：CSS 选择器。给不出 / 找不到 —— 气泡落在屏幕正中 */
  at?: string
  side?: GuideSide
  /** 这一步的标题（梅芙的一句话结论） */
  title: string
  /** 正文：一行一件事，别写长段 */
  lines: string[]
}

export interface GuideTour {
  id: string
  /** 只在某个模块里出现；不给 = 全局 */
  view?: string
  /**
   * 绑在哪个**界面**上（不是模块）：只认 'battle'。
   * 用它那两段讲的不是某个模块怎么用，而是**这一场怎么打** ——
   * 所以它们既不该在切模块时撤、也不该在退出作战屏之后赖着不走（见 Guide 的轮询）。
   */
  field?: 'battle'
  /**
   * 这一段算**教程**（气泡右下角给「跳过教程」）。
   * 绑在界面上、没有 view 的那两段默认不算教程 —— 但作战基础那一段算：
   * 它就是教程的一部分，只是讲台摆在战场上。玩家明说过「别再讲了」的时候，
   * 这一条得听他的。唯独 boss 那一段不在此列（见 BOSS 的注释）：
   * 那时候不解释是要死人的。
   */
  tutorial?: boolean
  steps: GuideStep[]
}

