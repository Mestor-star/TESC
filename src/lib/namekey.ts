/* ============================================================
   lib/namekey.ts — 名字归一化（全仓唯一的一把尺）

   数据表里同一个名字的「中点」不是一个字符：档案/图鉴多写「・」(U+30FB)，
   正文与部分名册写「·」(U+00B7)，另有 U+2027「‧」与半角「･」(U+FF65)。
   凡是拿名字认人的地方，照原始字符串精确匹配就会整条丢掉（推荐名单解析
   不出人、世界书条目认不出说话人、图鉴实体登记漏条）。

   所以「建表」与「查表」共用这一个函数：
     NFKC（兼容字符先拉平）→ 去掉全部空白 → 四种中点统一 U+00B7。
   它只产出**比较键**，绝不用于上屏 —— 显示名一个字都不改。
   ============================================================ */

/** 四种中点（U+00B7 / U+2027 / U+30FB / U+FF65），NFKC 之后仍可能是后三种 */
const MID_DOTS = /[\u00b7\u2027\u30fb\uff65]/g

/** 统一到的那一个中点（只做比较键用） */
const MID_DOT = '\u00b7'

/** 名字 → 比较键：NFKC + 去全部空白 + 中点统一 U+00B7。只用于比较，不改显示名。 */
export function nameKey(raw: string): string {
  return raw.normalize('NFKC').replace(/\s+/g, '').replace(MID_DOTS, MID_DOT)
}
