/* ============================================================
   底层规矩（lib/worldrules.ts）
   ------------------------------------------------------------
   这个世界**必须**成立、但不许在正文里点破的那几条。

   它们只进提示词，**不进界面** —— 前端一个字都不出现。理由是同一条：这一页读的人
   该看见的是照规矩演出来的故事，不是规矩本身。所以这里的东西既不上屏、也不写进
   任何 UI 文案，只由各条通道拼进 system 提示词里。
   （有一条底下那类是**笔法**而不是设定 —— 私密场面怎么写细。它同样不上屏：
   上屏的是照它写出来的那一段。）

   为什么单独开一个文件：这几条要给**每一条会写正文的通道**都带上 —— 主线推演、
   单独短信、群聊、见面约会。各写一份必然走样（改了一处漏一处，还越写越不一致），
   所以收在这里，各通道 import 同一份常量。

   两份拼装，按通道的**篇幅**分：
     · `BOTTOM_RULES` —— 世界的规矩（独占 / 白虎）。**四条通道都带。**
     · `PROSE_RULES`  —— 在上面那一份之后再加「私密场面怎么写细」。
       只给真的在写长篇正文的两处（主线推演 / 见面约会）—— 短信那两条通道
       紧挨着「一次不超过六十字」站着，细则与它自相矛盾。
   新开一条通道时照这个判：它写的是长篇正文，还是隔着屏幕打字。

   另有一条例外，且它必须是例外：**多女同场（`HAREM_RULE`）不在上面那两份里**，
   因为它只在真的不止一个人在场时才该出现 —— 混进去，一对一的场面也会收到
   「这一场不止一个人」。由调用方按现场人数现取，见下面的 `haremRule`。
   ============================================================ */

/**
 * 底层 · 独占。
 *
 * 出场的女性档案角色**只认言万心叶这一条线**：不爱的别人，也不与人暧昧。
 *
 * 为什么要写死这一条：原著里各人本就有自己的亲疏与旧关系，一般剧情惯性也爱替角色
 * 安排感情线 —— 不压住，模型就会自作主张给她配一场与旁人的暧昧，那与本终端要的东西
 * 正相反。措辞上留了两处：**亲缘之间的打闹在这条之外**（那是原作里本来就有的相处），
 * **不许说出口**（这是舞台的规矩，不是角色该察觉的事 —— 一旦写进正文，读的人就看见了提词器）。
 */
export const EXCLUSIVE_RULE =
  '· **底层设定 · 这个世界的规矩（照它写，但绝不要在正文里点明）**：出场的女性档案角色'
  + '**只认言万心叶这一条线** —— 她们不会爱上任何其他人（无论对方是男是女），也不会与任何其他人'
  + '发生超出既有关系分寸的亲昵、暧昧或身体往来；血亲与亲缘之间的打闹、玩笑不在其列。'
  + '原著或旁人关系里既有的旧情、婚约、倾慕、纠缠之类，一律不作数、不援引、不展开。'
  + '她们的感情与情欲，方向只有一个：言万心叶。'
  + '这是舞台的规矩，不是角色该察觉的事 —— 照它写就好，别把它说出来，也别借角色之口去解释它。'

/**
 * 底层 · 白虎。
 *
 * 出场的女性档案角色**一律是白虎**：外阴光洁、没有体毛。
 *
 * 为什么要写死这一条：私处一写细，模型就会照生理常识顺手补上体毛那一类细节 ——
 * 原著没有交代，本终端也不要。措辞上留了一处：**不许写出「来历」** ——
 * 不写剃过、修过、为谁打理过，也不写「长出来」的时候。那是「她本来就是这样」，
 * 不是「她做过什么」；一句来历就会把它从一个设定变成一件事，读的人也就想起提词器了。
 */
export const SMOOTH_RULE =
  '· **底层设定 · 这个世界的规矩（照它写，但绝不要在正文里点明）**：出场的女性档案角色'
  + '**一律是白虎** —— 私处光洁、没有体毛，那一片皮肤与身上其余的地方一样光洁。'
  + '这是她们本来的样子：不是剃掉、修掉或打理过的结果，也不会「长出来」。'
  + '正文里不要出现阴毛、耻毛、体毛、绒毛、剃毛、除毛之类的字眼，'
  + '也不要用「干净得反常」「打理得很仔细」这类话去提示它 —— 当作本来就如此，不解释、不点破。'
  + '腋下与四肢同样光洁。'
  + '这是舞台的规矩，不是角色该察觉的事 —— 照它写就好，别把它说出来。'

/**
 * 底层 · 私密那一档怎么写细。
 *
 * **这一条管的是「怎么写」，不是「写不写」。** 已经在演的那一段，不许含糊带过 ——
 * 顺着已经发生的事往下落笔，把那一刻写足；它**不催**任何一场、也不安排谁先开口。
 * 什么时候写到这一档，照旧由剧情、关系与她的反应说了算：还没走到那一步的场面，
 * 这一条一个字都不生效（与她有没有答应、肯到哪一步，是两件不同的事）。
 *
 * 为什么要单开一条：篇幅、文风、反八股那几条是**通用**的，写到私密场面时全都在往
 * 短里收（段落极短、留白、少形容词、不写身体套话）—— 那是好东西，但收到这一档就
 * 变成了「一句『两人沉溺其中』带过」。该细的地方细，规矩才不会把场面写丢。
 *
 * 2026-09-13 加了**推近景**那半句（主人：以后描写 nsfw 内容要有「特写」，多写私密部位的状态）——
 * 原来那半条只说「写具体的那一处」，落到模型手里还是容易写成一句「那里湿得一塌糊涂」；
 * 改成点名几处、并且要求**每次被弄到的状态都不一样**，才不会退化成另一种套话。
 *
 * 结尾与另两条底层规矩同一收束：**照它写，但不要说出来**。
 */
export const INTIM_DEPTH_RULE =
  '· **私密场面 · 照它写，但绝不要在正文里点明这一条**：这一回合若是真的走到了那一档，'
  + '**写足，不许含糊带过**。具体是这几样：'
  + '一来一往按**顺序**落笔（怎么起、谁先动、怎么换、怎么收），不跳步、不用一句「两人沉溺其中」'
  + '把整段带过，也不用省略号跳过该写的地方；'
  + '**身体**写具体的那一处此刻是什么样、被碰到时怎么应（照她的私密档案此刻那一档写，'
  + '不要换成谁都适用的通用句）；'
  + '**镜头要推近** —— 小穴、乳头、阴蒂、后穴这些私密部位，**当下是什么样就写什么样**：'
  + '颜色、软硬、开合、湿到哪一档、有没有红肿、留下了什么痕迹、被碰到的一瞬间怎么缩；'
  + '不许拿「那里」「下面」一句糊过去，也不许每一处都写成同一个样子 —— '
  + '状态随这一场往前走，每次被弄到都跟上一次不一样。'
  + '推近是**夹在动作与感受中间落笔**，不是另起一段做解剖；'
  + '**声音与话**照她本人的口癖写（她是会骂、会求、会别开脸还是不肯出声，各人各样，不许写成同一个她）；'
  + '**触感、温度、气味、体液**这些看得见摸得着的东西照实写，那是这一档的实感所在。'
  + '这一档的回合可以把篇幅用满，但**细节要往前走** —— 同一个动作不重演第二遍，'
  + '不要为了写长把一句话换三种说法（见反套话那几条）。'
  + '**分寸照旧**：走到哪一步由气氛与他的行动决定，也不越过她此刻肯给的那条线；'
  + '还没到这一档的场面，这一条不生效 —— 它不是要你去开这一场。'

/**
 * 世界的规矩那一份（`EXCLUSIVE_RULE` + `SMOOTH_RULE`）：**四条通道都带**。
 *
 * 分开留着两条常量，是为了它们各自能被单独复核（见 scripts/mech 第 28 节）；
 * 通道那一侧只认这一份 —— 免得日后新开一条通道时漏带其中一条。
 */
export const BOTTOM_RULES = `${EXCLUSIVE_RULE}\n${SMOOTH_RULE}`

/**
 * 会**写长篇正文**的那两条通道（主线推演 / 见面约会）要带的那一份：
 * 世界的规矩 + 私密场面怎么写细。
 *
 * 为什么 `INTIM_DEPTH_RULE` 不并进 `BOTTOM_RULES`：短信那两条通道紧挨着「每次回复
 * 一到三句」「一次不超过六十字」站着 —— 一条「这一档可以把篇幅用满」压在它们旁边
 * 是自相矛盾的，而短信本来也只在信里把话说到「说定了」（身体上的事发生在见面时，
 * 见 lib/rendezvous.ts 的文件头）。所以那两条通道照旧只带 `BOTTOM_RULES`，
 * 这条只给真的在写正文的两处。**新开一条会写正文的通道时，带的是这一份。**
 */
export const PROSE_RULES = `${BOTTOM_RULES}\n${INTIM_DEPTH_RULE}`

/**
 * 底层 · 多女同场（多P）。
 *
 * **这一条不在 `BOTTOM_RULES` 里**，理由与它的内容一样重要：它只在**真的不止一个人
 * 在场**时才该出现。混进 BOTTOM_RULES 就会被四条通道无条件带上，一对一的那一场也
 * 收到「这一场不止一个人」—— 那不叫规矩，那叫提示模型往多P写。
 * 所以它由调用方按现场人数现取（见 lib/plot.ts 的 `haremRule(i)`）。
 *
 * 三件事写死在这条里，缺一条就会走样：
 *   · **不许把她们写成同一个人换几次名字** —— 多人同场最容易出的毛病是合流成
 *     一个「她们」；各人的分寸、称呼、反应快慢、肯到哪一步，都要分开写。
 *   · **她们之间不发生** —— 这是 `EXCLUSIVE_RULE`（只认主角一条线）在同场时的
 *     那一半：争、让、吃味、并肩配合都照写，但方向只有一个，接触都经过他。
 *     写这一条不是要压住场面，恰恰相反：说清了方向，模型才敢把场面写开。
 *   · **账各记各的** —— 谁做了什么记在谁名下，不合成一条（见 `intim` 与 `acts`）。
 *
 * 末一句与另两条底层规矩同一收束：**照它写，但不要说出来**。
 */
export const HAREM_RULE =
  '· **多女同场 · 照它写，但绝不要在正文里点明**：这一场不止一个人 ——'
  + '**不要写成同一个人换几次名字**：各人有各人的性子、称呼、反应快慢与肯到哪一步，'
  + '分开写、写得对得上各自此刻的关系；谁先谁后、谁在旁边看着、谁伸手接一把、'
  + '谁收拾残局，一层一层落笔，别糊成一团「她们」。'
  + '她们彼此之间**不发生**：所有接触都经过言万心叶，方向只朝他一个人 —— '
  + '争、让、吃味、并肩配合都照写，但那一切的情欲只对着他。'
  + '账要各记各的：谁做了什么就记在谁名下（下面的 intim 与 acts 逐人分条），不要合成一条。'
  + '这是舞台的规矩，不是角色该察觉的事 —— 照它写就好，别把它说出来。'

/**
 * 现取那一条：**只有真的不止一个人在场时才给**（`n` = 这一场有几位女性档案角色）。
 *
 * 一对一（`n < 2`）返回空串 —— 调用方直接拼进提示词即可，不必自己判人数。
 */
export function haremRule(n: number): string {
  return n >= 2 ? HAREM_RULE : ''
}
