/**
 * 敌体五轴的**唯一**算法。
 * ------------------------------------------------------------
 * 为什么要有这么一个函数：五轴原先散在两处算 —— 现推观测体的那一份写在
 * derive 的 buildFoe 里，图鉴实体（endfoes.ts）那一份又得另算一遍。
 * 两处一旦各写各的，「同危险度站上来一样厚」这句话就是假的：
 * 图鉴上写着 Stage8 的那只，可能比现推的同阶段首领软一大截。
 * 所以曲线只在这里，两个调用方都从这儿取，只是各传各的倍数。
 *
 * 参数说明：
 *   · `stage` 是**危险度**。现推观测体传任务阶段；图鉴实体传图鉴登记的 Stage
 *     （那个数就是委员会给它评的危险度，与任务阶段同一根标尺）。
 *   · `atkMul` / `willMul` 是档位倍数（首领 1.3 / 1.25，精英 1.15 / 1.12）——
 *     现推那一支要乘，图鉴实体**也乘**：它们个个是首领那一档，
 *     不乘的话图鉴实体会比同危险度的现推首领轻一档。
 *   · `progressMul` 是时期增幅（×1~×1.55）—— 只有现推观测体吃这一层。
 *     指名首领与图鉴实体都不吃：档案上是多少，打起来就是多少。
 *   · `rMul` 是地点 R 值增幅，只落在反现实亲和上（理由见 rvalue.ts 文件头）。
 */
export function enemyAxesAt(stage: number, o: {
  atkMul?: number
  willMul?: number
  progressMul?: number
  rMul?: number
} = {}): Record<AxisKey, number> {
  return {
    // 破坏力跟血量一起随时期走：只抬血的话，晚期的仗会变成
    // 「打不动我、我也打不死它」的干耗，那不是难度，是拖时间。
    破坏力: Math.round((TUNING.enemyAtkBase + stage * TUNING.enemyAtkPerStage)
      * (o.atkMul ?? 1) * (o.progressMul ?? 1)),
    敏捷度: Math.round(TUNING.enemySpdBase + stage * TUNING.enemySpdPerStage),
    物理抗性: Math.round(TUNING.enemyResistBase + stage * TUNING.enemyResistPerStage),
    反现实亲和: Math.round((TUNING.enemyAffBase + stage * TUNING.enemyAffPerStage) * (o.rMul ?? 1)),
    意志力: Math.round((TUNING.enemyWillBase + stage * TUNING.enemyWillPerStage) * (o.willMul ?? 1)),
  }
}

