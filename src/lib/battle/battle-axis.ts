/* ============================================================
   战斗侧五轴修正 —— **只进战场，不进档案**
   ------------------------------------------------------------
   一张表连着两头：`data/chars.ts` 的 stats 既是**档案页**印出来的那张
   （常态 / 极限两条读数），也是 `derive` 造战斗面板的底。
   于是「档案上写多少」与「打起来读多少」本来是一回事。

   这一张表把两头拆开：档案页照旧读官方五轴，战场读**转化过的那一份**
   （`battleAxisOf` 在 `derive` 造人那一步套上去，档案侧一个字都不经过它）。

   ------------------------------------------------------------
   「转化」是哪一步
   ------------------------------------------------------------
   2026-09-11 的**量程重标定**：战斗数值不再封顶之后，全表 24 人按同一组系数
   在放宽的量程上重排（原文锚一条未改、强弱次序一条未变，原读数越低的抬得越多）。
   那组系数就记在下头 `AXIS_RESCALE` 里，当时是逐条乘进 `chars.ts` / `SIDE_AXIS`
   的 —— 乘完的值既是档案读数，也是战斗读数。

   恋兔光那一份只走到一半：破 / 敏 / 亲三栏那天跟着动了，**物 49 与志 55
   还停在旧读数上**，于是她这个「RANK1 · 人类最强」的物抗与意志，在战场上
   比一整排登场者还低（凯特琳物 72、奈奈志 70）。

   主人 2026-09-16 定的口径：
     · **官方档案五轴一个字不改** —— 200 / 85 / 49 / 75 / 55 是原作给出的读数，
       档案页照旧印这一份；
     · **战斗系统的数值按同一组系数转化**，和她之外那 23 人一视同仁，
       不另外给她定一档。
   于是这里就是「官方 × `AXIS_RESCALE`」，一笔一笔写在下面。
   ============================================================ */

import type { AxisKey, AxisSheet } from './types'

const AXES: AxisKey[] = ['破坏力', '敏捷度', '物理抗性', '反现实亲和', '意志力']

/** 量程重标定那一组系数 —— 全表 2026-09-11 那一批乘的就是这几个 */
export const AXIS_RESCALE: AxisSheet = {
  破坏力: 2.2, 敏捷度: 1.9, 物理抗性: 1.5, 反现实亲和: 1.7, 意志力: 1.35,
}

/**
 * 键 = 名册 id，值 = **战斗侧那一份评定尺读数**（绝对值，不是加点、不是倍数）。
 * 只写要改的那几栏，其余沿用档案读数。
 *
 * ⚠️ 加人之前先问三句：档案页那张卡是不是该原样留着？乘的是不是全表同一组系数？
 * 乘完之后的强弱次序还对不对得上 RANK？（这里只该收「该转化却漏了」的人，
 * 不该收「想给她开小灶」的人 —— 开小灶请回 chars.ts，那是另一笔账。）
 */
export const BATTLE_AXIS: Record<string, Partial<AxisSheet>> = {
  /* 恋兔光：官方档案 破200 / 敏85 / 物49 / 亲75 / 志55 × 那一组系数
       破 200 × 2.2  = 440
       敏  85 × 1.9  = 161.5 → 162
       物  49 × 1.5  = 73.5  → 74
       亲  75 × 1.7  = 127.5 → 128
       志  55 × 1.35 = 74.25 → 74
     连带涨的是战斗生命（hpBase ＋ 物抗×hpPerResist ＋ 意志×hpPerWill，见 derive）
     ——「人类最强」本来就该是站得最久的那个。 */
  hikari: { 破坏力: 440, 敏捷度: 162, 物理抗性: 74, 反现实亲和: 128, 意志力: 74 },
}

/**
 * 把战斗侧那一份套到一份**评定尺**的五轴上。档案侧（`Archive.tsx` 直接读
 * `chars.ts` / `SIDE_AXIS`）不经过这里 —— 那条路一个字都不会变。
 */
export function battleAxisOf(id: string, axes: AxisSheet): AxisSheet {
  const fix = BATTLE_AXIS[id]
  if (!fix) return axes
  const out = { ...axes }
  for (const k of AXES) {
    const v = fix[k]
    if (typeof v === 'number') out[k] = v
  }
  return out
}
