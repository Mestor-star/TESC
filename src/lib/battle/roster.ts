/* 挂回名册：ROSTER 是「谁是什么定位、会哪几手」的唯一出处，
   被动同属那一份档案，故在此处一并合上，不再另建一张 id → 被动的表。
   天赋那几笔在这里过一次效果带（`bandedEffect`）—— 天赋不进 `place()`，
   要是不在这儿夹一道，它就整条绕过了「数字有上界」那条规矩。 */
for (const id in PASSIVE) {
  const r = ROSTER[id]
  if (!r) continue
  const p = PASSIVE[id]
  for (const t of p.talents ?? []) if (t.effect) t.effect = bandedEffect(t.effect)
  r.passive = p
}

/* ============================================================
   职能白名单 —— 「谁许挑哪几类框架」从文档落成机制
   ------------------------------------------------------------
   主人 2026-09-15 拍的口径：**本职 ＋ 一手通用**（见 duty.ts 的 UNIVERSAL_ARCH）。
   这一栏原先只写在 `DutyDef.arch` 的注释里，全靠人自觉；现在由这里落成断言 ——
   数据写歪了，导入的那一瞬间就红，不必等到某一手在战场上打出个不该有的东西。

   三条一起才算合规：
     · 战技格手数落在 [2, duty.arts]：少了两手拼不出战术，多了没有固定技能组可言；
     · 每一手要么是**本职**（在最前面认），要么占掉那唯一一手**通用**；
     · 至少留一手本职 —— 全挑通用手，这个人就没有职能，那五档的名字也就白起了。

   ⚠️ 恋兔光一人破例（`dutyExempt`，见 duty.ts 头注）：她六手原样挂着，整条跳过。
   ============================================================ */

export function assertDutySlots(): string[] {
  const bad: string[] = []
  for (const id in ROSTER) {
    const r = ROSTER[id]
    if (!r || r.dutyExempt) continue
    const d = dutyOf(r.duty)
    const arts = r.skills.filter((k) => k.kind === '战技' && !k.gate)
    let own = 0
    let universal = 0
    for (const k of arts) {
      const arch = k.arch ?? ''
      // 本职先认，认不上才轮到那一手通用 —— 护卫的「屏障」、和音的「治愈」
      // 两边名单里都有，交叉的那些按本职算，不然他们会自己占掉自己的名额。
      if (d.arch.includes(arch)) { own += 1; continue }
      if (UNIVERSAL_ARCH.includes(arch)) { universal += 1; continue }
      bad.push(`${id}：战技「${k.name}」按「${arch}」打，而 ${d.name} 这一档不许挑它`)
    }
    if (arts.length < 2) bad.push(`${id}：战技只有 ${arts.length} 手（下限 2 —— 少了两手拼不出战术）`)
    if (arts.length > d.arts) bad.push(`${id}：战技 ${arts.length} 手，超过 ${d.name} 的 ${d.arts} 手上限`)
    if (universal > UNIVERSAL_MAX) bad.push(`${id}：通用手占了 ${universal} 手（名额只有 ${UNIVERSAL_MAX}）`)
    if (arts.length > 0 && own === 0) bad.push(`${id}：一手本职都没有 —— 全挑通用手，这个人就没有职能`)
  }
  return bad
}

/* 导入即校验（与 `place()` 越界即抛同一个来路：数据错了就该当场响，
   不要留着到战场上表现得「有点怪」）。 */
const SLOT_BAD = assertDutySlots()
if (SLOT_BAD.length) throw new Error('职能白名单越界：\n  ' + SLOT_BAD.join('\n  '))

/* ============================================================
   被动的读数 —— 把字段翻成人话
   ------------------------------------------------------------
   档案里以前只印被动的那句原文说明，一个数都不给：读的人没法学
   「他到底强在哪」。这里按字段逐条摊开，有几个念几个；
   一个都没有的会被标成「未写效果」——那是漏写，不是没有。
   ============================================================ */

const pct = (v: number) => `${v > 0 ? '+' : ''}${Math.round(v * 100)}%`

export function passiveText(p?: PassiveSpec): string[] {
  if (!p) return []
  const out: string[] = []
  /* 这两条走的是**空转那一格**（`advance` 里逐格推的那一圈），不是「每一拍」：
     一回合里要空转好几格，写成「每拍」会让人把这个数读小好几倍（见 engine 的恢复途径②）。 */
  if (p.regen) out.push(`充能每格回血 ${pct(p.regen)}`)
  if (p.tempoRegen) out.push(`充能每格回节拍 ${p.tempoRegen}`)
  if (p.tempoMaxUp) out.push(`节拍上限 ${p.tempoMaxUp > 0 ? '+' : ''}${p.tempoMaxUp}`)
  if (p.shield) out.push(`常驻减伤 ${pct(p.shield)}`)
  if (p.atk) out.push(`常驻攻击 ${pct(p.atk)}`)
  if (p.lowHpAtk) out.push(`残血时攻击再 ${pct(p.lowHpAtk)}`)
  if (p.spd) out.push(`常驻充能 ${pct(p.spd)}`)
  if (p.evade) out.push(`常驻闪避 ${pct(p.evade)}`)
  if (p.acc) out.push(`常驻命中 ${pct(p.acc)}`)
  if (p.sureHit) out.push('出手必中')
  if (p.headStart) out.push(`开场行动条领先 ${pct(p.headStart)}`)
  if (p.cdCut) out.push(`冷却每拍多减 ${p.cdCut}`)
  if (p.basicMul) out.push(`普攻倍率 ${pct(p.basicMul)}`)
  if (p.endure !== undefined) {
    const plus = p.endurePlus ? `，${personOf(p.endurePlus.with)?.name ?? p.endurePlus.with}在场时 ${p.endure + p.endurePlus.extra} 次` : ''
    const base = p.endure < 0 ? '致命伤不死（不限次）' : `致命伤留 1 点（每场 ${p.endure} 次）`
    out.push(base + (p.endure < 0 ? '' : plus))
  }
  /* 天赋（四格制的第四格）也算「这个人一直带着的东西」，一并念出来 ——
     它不进 `skills`（点不了），要是不在这儿补一句，档案上就整条看不见它。 */
  for (const t of p.talents ?? []) out.push(talentLineOf(t))
  return out.length ? out : ['未写效果 —— 这一条要补']
}
