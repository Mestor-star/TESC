/* ============================================================
   战斗中「换武装 / 用道具」的两条口径（依主人 2026-09-21 要求）
   ------------------------------------------------------------
   ① 换武装（军需里的装具）**不消耗回合**：不扣行动条、不推进行动条、
      不结束这一手 —— 换完这个人还站在待令位上，照样出得了招。
      次数落在 `SWAP_PER_BEAT`（**1 次/回合**，理由见那一格的头注）。
   ② 道具**不再计数、也不消耗回合**：背包不扣数，一回合里想丢几剂就几剂，
      丢完立刻还能出招。
   两条都**不走 beginAction**（见 engine 的 act）—— 那一句「不走」才是
   「不耗回合」的实体：不扣条、不减冷却、不扣增益时限、不记手数、
   不登记本回合已出手、不蓄追击槽。

   这个模块只管**判**：能不能换成这一件、屏上该写什么读数。
   落地在 engine 的 equip/swap 与 item 两支，把手在 Battle.tsx。
   ============================================================ */

import { GEAR_OF, canEquip } from './gear'

/**
 * 换武装每回合几次 —— **1 次**。
 *
 * 为什么不给「随便换」：换装是**整块重算面板**（轴值 / 充能 / 闪避 / 减伤 /
 * 附带技能全换一份），它不进行动条也不扣冷却，等于白拿一次面板重排。
 * 若一回合里可以无限换，玩家会按「这一手要打谁」临时凑五轴，
 * 装具就从「编成时的取舍」退化成「出招前的临时 buff」，那条取舍也就没了。
 * 1 次仍留得下「这一拍换件对路的再打」这种决策，所以取 1。
 */
export const SWAP_PER_BEAT = 1

/**
 * 道具在战斗中**不计数**（无限）。
 *
 * 主人原话：「道具…在战斗中可以无限使用，不消耗回合」。
 * 于是背包那一格不再扣数、也不再当闸；`BattleState.bag` 保留原样
 * （存档读写那一头还要它），只是引擎不再读它的余量。
 */
export const ITEM_UNLIMITED = true

/** 屏上那一格读数：不再是「×N」，改成一个词。 */
export const ITEM_COUNT_LABEL = '不限'

/**
 * `data-bag-count` 的值 —— **常量**，不是数量。
 *
 * 那条属性是冒烟和外部脚本读的把手，语义变了但把手不能消失，
 * 所以给它一个稳定的常量值（不是把「剩余几剂」写进去）。
 */
export const ITEM_COUNT_ATTR = 'inf'

/** 换武装的判词：能不能换成这一件（`gearId = null` = 卸下）。 */
export interface SwapVerdict {
  ok: boolean
  /** 换不成的理由 —— 直接写进日志给玩家看，别让人按下去没反应 */
  why?: string
}

/**
 * 能不能换成这一件。
 *
 * 三道门，顺序即优先级：
 *   ① 卸下永远允许（空手也不是罪）；
 *   ② 这件得**在背包里**（`owned` 是军需库存；旧入口 / 复核脚本不传就只认后两道）；
 *   ③ 这个人得**装得上**（`canEquip`：专属件认人，露娜的丝线只认言万心叶）。
 * 「一件装具只有一副」是队伍层的事（同一个 id 不能挂在两个人身上），
 * 那一关在 Battle.tsx 的编成映射上拦，引擎这边不重复判 —— 引擎只看得到
 * 这一场开打时的那一份编成。
 */
export function canSwapTo(
  charId: string,
  gearId: string | null,
  owned?: Record<string, number>,
): SwapVerdict {
  if (!gearId) return { ok: true }
  const g = GEAR_OF[gearId]
  if (!g) return { ok: false, why: '军需里没有这一件' }
  if (owned && (owned[gearId] ?? 0) <= 0) return { ok: false, why: `${g.name} 不在背包里` }
  if (!canEquip(charId, gearId)) {
    return { ok: false, why: `${g.name} 认人 —— 换个人拿在手里也只是一件死物` }
  }
  return { ok: true }
}
