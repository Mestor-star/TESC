import { assetBase } from './assetbase'

const SEEN_KEY = 'zts-pv-seen'

const REPO = 'Mestor-star/TESC'
/** 钉住的那一支：换 `public/pv.mp4` 之后，改这里（见文件头那条 ⚠） */
const PV_PIN = '22f3d84'

/**
 * 片子的候选源，**按「谁一定取得到」排**：① 本站 → ② jsDelivr（CDN）。
 * 本站那条是页面自己来的路 —— 页面打开过，它就一定通，所以它排头；
 * CDN 只在本站真的出错（`onError`）时才试。
 *
 * ⚠ 别按「谁快」排。这条国际线的快慢**在抖**（同一天量到过 274.7 KB/s，也量到过 0 B/s），
 * 一次采样排出来的次序，换个钟点就是反的 —— 见文件头 ② 那段。
 */
export function pvSources(): string[] {
  return [
    /* 跟着 `assetBase()` 走，GitHub Pages 那种子路径站也取得到 */
    `${assetBase()}pv.mp4`,
    `https://cdn.jsdelivr.net/gh/${REPO}@${PV_PIN}/public/pv.mp4`,
  ]
}

export function hasSeenPv(): boolean {
  try {
    return localStorage.getItem(SEEN_KEY) === '1'
  } catch {
    return true
  }
}

export function markPvSeen(): void {
  try {
    localStorage.setItem(SEEN_KEY, '1')
  } catch {
    /* 存不下就算了：这一趟已经放过了，最坏是下次开还放一遍 */
  }
}

/* ------------------------------------------------------------------
   片子在不在 —— 一个 10 行的极小仓，给「重看」那枚按钮照着隐身
   （与 `lib/sms.ts` 的 `subscribeUnread` / `totalUnread` 同一套读法：
     `useSyncExternalStore(subscribePvOk, pvOk)`）。
   `null` = 还不知道（没放过）；true / false 是实际放出来的结果。
   ------------------------------------------------------------------ */
let ok: boolean | null = null
const subs = new Set<() => void>()

export function pvOk(): boolean | null {
  return ok
}

export function notePvOk(v: boolean): void {
  if (ok === v) return
  ok = v
  subs.forEach((f) => f())
}

export function subscribePvOk(f: () => void): () => void {
  subs.add(f)
  return () => {
    subs.delete(f)
  }
}
